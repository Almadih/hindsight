"""One-off: build src/review/eco_data.py (EPD -> "ECO Name") from lichess-org/chess-openings.

A .py module, not JSON: Python Workers only bundle Python modules.

Run: uv run python scripts/build_eco.py
"""

import csv
import io
import json
import pathlib
import urllib.request

import chess.pgn

BASE = "https://raw.githubusercontent.com/lichess-org/chess-openings/master/{}.tsv"
OUT = pathlib.Path(__file__).parent.parent / "src" / "review" / "eco_data.py"

book: dict[str, str] = {}
for part in "abcde":
    text = urllib.request.urlopen(BASE.format(part)).read().decode()
    for row in csv.DictReader(io.StringIO(text), delimiter="\t"):
        board = chess.pgn.read_game(io.StringIO(row["pgn"])).end().board()
        # Transpositions reach the same position under several names; keep the first one seen.
        book.setdefault(board.epd(), f'{row["eco"]} {row["name"]}')

OUT.write_text("# Generated by scripts/build_eco.py, do not edit.\nBOOK = " + json.dumps(book, separators=(",", ":")) + "\n")
print(f"{len(book)} positions -> {OUT}")
